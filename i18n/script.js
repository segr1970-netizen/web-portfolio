function setLanguage(lang) {
    if (!translations[lang]) lang = 'sv';
    
    // Update html lang attribute
    document.documentElement.lang = lang;
    
    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            if (el.tagName === 'TITLE') {
                document.title = translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });

    // Update active button state
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
            btn.setAttribute('aria-pressed', 'true');
        } else {
            btn.classList.remove('active');
            btn.setAttribute('aria-pressed', 'false');
        }
    });

    // Save choice (Safe try-catch for LocalStorage)
    try {
        localStorage.setItem('pref_lang', lang);
    } catch (e) {
        console.warn("Could not save language preference to localStorage.");
    }
}

// Auto-detect language or use saved
document.addEventListener('DOMContentLoaded', () => {
    let savedLang = null;
    
    // Safe try-catch for LocalStorage
    try {
        savedLang = localStorage.getItem('pref_lang');
    } catch (e) {
        console.warn("Could not read language preference from localStorage.");
    }

    const userLang = (navigator.language || navigator.userLanguage || '').slice(0, 2).toLowerCase();
    
    let defaultLang = 'sv'; // Default for Swedish course
    if (savedLang && translations[savedLang]) {
        defaultLang = savedLang;
    } else if (translations[userLang]) {
        defaultLang = userLang;
    }

    setLanguage(defaultLang);

    // Event listeners
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const chosenLang = btn.getAttribute('data-lang');
            setLanguage(chosenLang);
        });
    });
});
